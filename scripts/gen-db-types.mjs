#!/usr/bin/env node
// M0-B4 — Generate TypeScript types from the database schema.
//
// Writes the same file to two places:
//   packages/shared/src/db.ts          → used by apps/web, apps/admin (and later apps/mobile)
//   supabase/functions/_shared/db.ts   → used by Edge Functions (the Supabase deploy bundler
//                                        only ships files inside supabase/functions/)
//
// Usage:
//   node scripts/gen-db-types.mjs                       # from local DB (needs `supabase start` or `supabase db start`)
//   node scripts/gen-db-types.mjs --linked              # from the project you ran `supabase link` against
//   node scripts/gen-db-types.mjs --project-id <ref>    # from a specific cloud project
//   node scripts/gen-db-types.mjs --check               # exit 1 if the files are out of date (CI)
//
// Never edit db.ts by hand — change a migration, then re-run this script.

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGETS = ["packages/shared/src/db.ts", "supabase/functions/_shared/db.ts"];
const SCHEMAS = "public";

const args = process.argv.slice(2);
const check = args.includes("--check");

let source = ["--local"];
if (args.includes("--linked")) source = ["--linked"];
const idx = args.indexOf("--project-id");
if (idx !== -1) {
  const ref = args[idx + 1];
  // Project refs are 20 lowercase letters/digits; validating also keeps the shell command safe.
  if (!/^[a-z0-9]{20}$/.test(ref ?? "")) fail("--project-id needs a valid project ref");
  source = ["--project-id", ref];
}

function fail(msg) {
  console.error(`gen-db-types: ${msg}`);
  process.exit(1);
}

// One command string (all parts are fixed or validated above). A shell is needed so Windows
// can run the npm-installed `supabase.cmd` shim.
const command = ["supabase", "gen", "types", "typescript", ...source, "--schema", SCHEMAS].join(" ");
const result = spawnSync(command, {
  cwd: root,
  encoding: "utf8",
  shell: true,
  maxBuffer: 64 * 1024 * 1024,
});

if (result.error) fail(`could not run the Supabase CLI: ${result.error.message}`);
if (result.status !== 0) {
  process.stderr.write(result.stderr);
  fail(
    source[0] === "--local"
      ? "type generation failed. Is the local DB running? Try `supabase db start`."
      : "type generation failed (see above).",
  );
}

const body = result.stdout.replace(/\r\n/g, "\n").trimEnd();
if (!body.includes("export type Database")) fail("unexpected CLI output (no `Database` type)");

// No timestamp in the header: output must be identical for an unchanged schema, so --check works.
const content =
  `// AUTO-GENERATED by scripts/gen-db-types.mjs from the "${SCHEMAS}" schema. DO NOT EDIT.\n` +
  `// Regenerate: pnpm db:types  (or: node scripts/gen-db-types.mjs)\n\n` +
  body +
  "\n";

const stale = [];
for (const rel of TARGETS) {
  const file = resolve(root, rel);
  const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (current === content) continue;
  stale.push(rel);
  if (!check) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}

if (check) {
  if (stale.length) {
    fail(`out of date: ${stale.join(", ")}\nRun \`pnpm db:types\` and commit the result.`);
  }
  console.log("gen-db-types: types are up to date.");
} else {
  console.log(stale.length ? `gen-db-types: wrote ${stale.join(", ")}` : "gen-db-types: no changes.");
}
